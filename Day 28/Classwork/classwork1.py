# 1) პირდაპირ გამოიყენეთ string-ებზე lower, upper, capitalize,
#  მეთოდები კომენტარებით დაწერეთ რა არის მეთოდი რით 
# განსხვავდება ჩვეულებრივი 
# ფუნქციისგან, რა არის dot ნოტაცია. ასევე გააკეთეთ 3 მაგალითი
#  find მეთოდზე, აუცილებლად უნდა იყოს 3 შემთხვევა: 
# error, -1, რაიმე პოზიციას (index)

"Saba".lower()  # აქ ყველა ასო ხდება პატარა: "saba"

"Mumladze".upper()  # ყველა ასო ხდება დიდი: "MUMLADZE"

"Saba".capitalize()  # პირველი ასო ხდება დიდი, დანარჩენი პატარა: "Saba"

"Mumladze".find("z")  # აბრუნებს ინდექსს 6 — პირველი "z"-ს პოზიცია

"Mumladze".find("x")  # აბრუნებს -1 — "x" არ არის სტრინგში

"Mumladze".find()  # შეცდომა — find() მეთოდს სჭირდება არგუმენტი